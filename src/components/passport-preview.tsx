"use client";

import { useState } from "react";
import { LockKeyhole } from "lucide-react";
import type { Product } from "@/lib/catalogue";
import type { Locale } from "@/lib/languages";

export function PassportPreview({
  products,
  locale = "en",
}: {
  products: Product[];
  locale?: Locale;
}) {
  const french = locale === "fr";
  const [selected, setSelected] = useState(products[0].slug);
  const product = products.find((item) => item.slug === selected)!;
  return (
    <div className="passport-preview">
      <div className="passport-selector">
        <label htmlFor="passport-product">
          {french
            ? "Explorer une référence publique en développement"
            : "Explore a public development reference"}
        </label>
        <select
          id="passport-product"
          value={selected}
          onChange={(event) => setSelected(event.target.value)}
        >
          {products.map((item) => (
            <option key={item.id} value={item.slug}>
              {item.name}
            </option>
          ))}
        </select>
        <p className="small-note">
          {french
            ? "Cet aperçu utilise le catalogue. Il ne prouve pas la provenance du produit."
            : "This view uses catalogue previews. It does not establish product provenance."}
        </p>
      </div>
      <div className="passport-record" aria-live="polite">
        <div className="passport-record-header">
          <span className="eyebrow">
            {french
              ? "JULA Passport · Aperçu uniquement"
              : "JULA Passport · Preview only"}
          </span>
          <LockKeyhole size={22} strokeWidth={1} />
        </div>
        <h2>{product.name}</h2>
        <dl>
          <div>
            <dt>{french ? "Fiche de lot" : "Batch record"}</dt>
            <dd>{french ? "Non disponible" : "Not available"}</dd>
          </div>
          <div>
            <dt>{french ? "Origine envisagée" : "Origin direction"}</dt>
            <dd>
              {product.proposedOrigin ??
                (french ? "À confirmer" : "To be confirmed")}
              {product.proposedOrigin
                ? french
                  ? " · non vérifiée"
                  : " · unverified"
                : ""}
            </dd>
          </div>
          <div>
            <dt>{french ? "Producteur et récolte" : "Producer & harvest"}</dt>
            <dd>
              {french
                ? "Documents vérifiés et autorisations en attente"
                : "Pending verified records and permissions"}
            </dd>
          </div>
          <div>
            <dt>
              {french ? "Ingrédients et allergènes" : "Ingredients & allergens"}
            </dt>
            <dd>{french ? "Pas encore validés" : "Not yet approved"}</dd>
          </div>
          <div>
            <dt>{french ? "Préparation" : "Preparation"}</dt>
            <dd>{french ? "Pas encore validée" : "Not yet approved"}</dd>
          </div>
          <div>
            <dt>{french ? "Compte / accès QR" : "Account / QR access"}</dt>
            <dd>{french ? "Non actif" : "Not active"}</dd>
          </div>
        </dl>
        <p>
          {french
            ? "Les informations de lot vérifiées nécessitent un système de traçabilité et des documents approuvés. Cet aperçu ne génère ni code QR, ni certificat d'origine, ni preuve de producteur."
            : "Verified batch information will require a traceability system and approved source records. No QR code, origin certificate or producer evidence is generated by this preview."}
        </p>
      </div>
    </div>
  );
}
