export function translate(text: string, locale: Locale): string {
  return locale === "fr"
    ? (french[text] ?? navigationFrench[text] ?? text)
    : text;
}

export type Locale = "en" | "fr";

export function localeFromPath(path: string): Locale {
  const prefix = process.env.NEXT_PUBLIC_BASE_PATH ?? "";
  const local =
    prefix && path.startsWith(`${prefix}/`) ? path.slice(prefix.length) : path;
  return local === "/fr" || local.startsWith("/fr/") ? "fr" : "en";
}

export function languagePath(path: string, locale: Locale): string {
  const prefix = process.env.NEXT_PUBLIC_BASE_PATH ?? "";
  const local =
    prefix && path.startsWith(`${prefix}/`) ? path.slice(prefix.length) : path;
  const neutral = local.replace(/^\/fr(?=\/|$)/, "") || "/";
  return locale === "fr" ? `/fr${neutral === "/" ? "" : neutral}` : neutral;
}

